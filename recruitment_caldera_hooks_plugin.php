<?php
/*
* Plugin Name: Recruitment Caldera Hooks
* Description: Supplementary plugin to pass data from Caldera form submissions to the recruitment server
*/

$post_url = <RECRUITMENT POST ENDPOINT>
$get_url = <OPEN POSITION LIST ENDPOINT>
$certificate_location = plugin_dir_path( __FILE__ ) . <CERT FILE NAME>;
$request_port = 443;
$entry_id_global = '0';		// ID of the Caldera entry being processed. This is updated dynamically at runtime.

// hook into Caldera's automatic action for successful form submission
add_action( 'caldera_forms_submit_complete', function( $form, $referrer, $process_id ) {
	if ( $form['ID'] != <CALDERA FORM ID> ) {
		return; // failsafe to reject requests from any other Caldera forms that might be present on the site
	}
	
	$current_salary_id = 'fld_#######';
	$desired_salary_id = 'fld_#######';
	
	$sensitive_fields = array($current_salary_id, $desired_salary_id);
	
	// retrieve the values from each field of the Caldera form
	// field IDs are generated by Caldera as they're created, so the exact values will vary from instance to instance
	$first_name = Caldera_Forms::get_field_data( 'fld_#######', $form );
	$last_name = Caldera_Forms::get_field_data( 'fld_#######', $form );
	$phone_number = Caldera_Forms::get_field_data( 'fld_#######', $form );
	$email = Caldera_Forms::get_field_data( 'fld_#######', $form );
	
	$desired_position = Caldera_Forms::get_field_data( 'fld_#######', $form );
	
	$current_salary = Caldera_Forms::get_field_data( $current_salary, $form );
	$desired_salary = Caldera_Forms::get_field_data( $desired_salary, $form );
	
	$resume = Caldera_Forms::get_field_data( 'fld_#######', $form );
	$cover_letter = Caldera_Forms::get_field_data( 'fld_#######', $form );
	
	$body = array(
		'firstName' => $first_name,
		'lastName' => $last_name,
		'phone' => $phone_number,
		'email' => $email,
		'position' => $desired_position,
		'resume' => $resume
	);
	
	if ( $current_salary != null && $current_salary != "" ) {
		$body["currentSalary"] = $current_salary;
	}
	
	if ( $desired_salary != null && $desired_salary != "" ) {
		$body["desired_salary"] = $desired_salary;
	}
	
	if ( $cover_letter != null ) {
		$body["coverLetter"] = $cover_letter;
	}
	
	// use cURL to submit the form data to the recruitment API
	global $post_url;
	global $certificate_location;
	global $request_port;
	$ch = curl_init($post_url);
	curl_setopt($ch, CURLOPT_PORT, $request_port);
	curl_setopt($ch, CURLOPT_CUSTOMREQUEST, "POST");
	curl_setopt($ch, CURLOPT_POSTFIELDS, $body);
	curl_setopt($ch, CURLOPT_RETURNTRANSFER, true);
	curl_setopt($ch, CURLOPT_SSL_VERIFYPEER, true);
	curl_setopt($ch, CURLOPT_CAINFO, $certificate_location);
	curl_setopt($ch, CURLOPT_CAPATH, $certificate_location);
	curl_setopt($ch, CURLOPT_HTTPHEADER, array(
		"Content-Type: multipart/form-data"
	));
	
	error_log('~~~~~~ attempting POST request to ' . $post_url . ' ~~~~~~');
	$result = curl_exec($ch);
	
	if ( $curl_errno($ch) ) {
		$errstr = curl_errno($ch) . ": " . curl_error($ch);
		error_log($errstr);
	}
	else {
		error_log("Response code: ");
		error_log(curl_getinfo($ch, CURLINFO_HTTP_CODE));
	}
	
	curl_close($ch);
	
	// hide sensitive information in Caldera's stored entries
	global $entry_id_global;
	foreach ($sensitive_fields as &$field) {
		Caldera_Forms_Entry_Update::update_field_value( $field, $entry_id_global, "••••••");
	}
}, 100, 3);

// hook into Caldera's automatic action that occurs after a successful submission
add_action( "caldera_forms_submit_post_process", function( $form, $referrer, $process_id, $entry_id ){
	if ( $form['ID'] == <CALDERA FORM ID> ) {
		global $entry_id_global;
		$entry_id_global = $entry_id;
	}
}, 10, 4);

// customize the options of the Desired Position dropdown menu based on a response from the recruitment API
add_filter( "caldera_forms_render_get_field", function( $field ) {
	// positions list field (ID depends on the specific form instance
	if ( $field["ID"] == "fld_#######" ) {
		// use cURL to get the list of positions from the back-end service
		global $get_url;
		global $certificate_location;
		global $request_port;
		$ch = curl_init($get_url);
		curl_setopt($ch, CURLOPT_PORT, $request_port);
		curl_setopt($ch, CURLOPT_TIMEOUT, 60);
		curl_setopt($ch, CURLOPT_RETURNTRANSFER, 1);
		curl_setopt($ch, CURLOPT_SSL_VERIFYPEER, true);
		curl_setopt($ch, CURLOPT_CAINFO, $certificate_location);
		curl_setopt($ch, CURLOPT_CAPATH, $certificate_location);
		
		error_log("~~~~~~ attempting GET request to " . $get_url . " ~~~~~~");
		response = curl_exec($ch);
		
		if (curl_errno($ch)) {
			$errstr = curl_errno($ch);
			error_log($errstr);
		}
		else {
			error_log("Response code: ");
			error_log(curl_getinfo($ch, CURLINFO_HTTP_CODE));
		}
		
		curl_close($ch);
		
		// turn the response into a list of menu options
		$position_list = json_decode($response);
		
		// if GET is unsuccessful, and position_list is not populated, set placeholder options
		if ( !(is_array($position_list) && !empty($position_list)) ) {
			$position_list = array("Other");
		}
		
		foreach( $position_list as $option ) {
			$field["config"]["option"][$option] = array(
				"value" => $option,
				"label" => $option
			);
		}
	}
	
	return $field;
});